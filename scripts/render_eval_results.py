"""Render docs/eval_results.md from the database.

    python -m scripts.render_eval_results                 # the latest run
    python -m scripts.render_eval_results --run-id 7
    python -m scripts.render_eval_results --compare 3 7

Every number in the results table comes from here. Nothing in docs/ or README.md is typed
by hand, and this script is the only thing that writes docs/eval_results.md. If it has not
been run, the file says so rather than showing a stale number.
"""

from __future__ import annotations

import argparse
from datetime import UTC, datetime
from pathlib import Path

from sqlalchemy import select

from arcagent.persistence.db import session_scope
from arcagent.persistence.models import EvalResult, EvalRun
from arcagent.persistence.repo import EvalRepository
from evals import metrics

OUTPUT = Path(__file__).resolve().parents[1] / "docs" / "eval_results.md"

HEADER = """# Evaluation results

<!-- GENERATED BY scripts/render_eval_results.py. DO NOT EDIT BY HAND. -->

Every number here comes from a run in the database, tagged with a git sha and a prompt
version. The harness measures the agent against a fixed persona set: it measures
consistency and regression, not real world conversion.
"""

EMPTY = """# Evaluation results

<!-- GENERATED BY scripts/render_eval_results.py. DO NOT EDIT BY HAND. -->

No eval runs in the database yet.

    python -m evals.run_text --run-name baseline --repeats 3
    python -m scripts.render_eval_results
"""


def latest_run_id() -> int | None:
    with session_scope() as session:
        return session.scalar(select(EvalRun.id).order_by(EvalRun.id.desc()).limit(1))


def render_run(run: EvalRun, rows: list[EvalResult], groups: dict[str, str]) -> str:
    """One run as markdown. Spreads, never bare means."""
    lines = [
        HEADER,
        f"## {run.run_name}",
        "",
        f"- run id: `{run.id}`",
        f"- git sha: `{run.git_sha}`",
        f"- prompt version: `{run.prompt_version}`",
        f"- handoff threshold: `{run.threshold}`",
        f"- tier: `{run.tier}`",
        f"- run at: {run.created_at:%Y-%m-%d %H:%M} UTC" if run.created_at else "",
        f"- scenarios: {len({r.scenario_id for r in rows})}, results: {len(rows)}",
        "",
    ]

    counts = metrics.handoff_counts(
        [(bool(r.handoff_expected), bool(r.handoff_actual)) for r in rows]
    )
    accuracy = metrics.spread([r.field_accuracy or 0.0 for r in rows])
    completeness = metrics.spread([r.crm_completeness or 0.0 for r in rows])
    passes: dict[str, list[bool]] = {}
    for row in rows:
        passes.setdefault(row.scenario_id, []).append(bool(row.passed))

    lines += [
        "### Overall",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Pass rate | {sum(bool(r.passed) for r in rows) / len(rows):.1%} |",
        f"| Field extraction accuracy | {accuracy.mean:.3f} +/- {accuracy.stdev:.3f} |",
        f"| CRM completeness | {completeness.mean:.3f} +/- {completeness.stdev:.3f} |",
        f"| Handoff precision | {counts.precision:.3f} |",
        f"| Handoff recall | {counts.recall:.3f} |",
        f"| Flaky scenarios | {len(metrics.flaky_scenarios(passes))} |",
        "",
        "### By category",
        "",
        "| Group | Scenarios | Pass rate | Field accuracy | Handoff recall |",
        "|---|---|---|---|---|",
    ]

    by_group: dict[str, list[EvalResult]] = {}
    for row in rows:
        by_group.setdefault(groups.get(row.scenario_id, "unknown"), []).append(row)
    for group in sorted(by_group):
        group_rows = by_group[group]
        group_counts = metrics.handoff_counts(
            [(bool(r.handoff_expected), bool(r.handoff_actual)) for r in group_rows]
        )
        group_accuracy = metrics.spread([r.field_accuracy or 0.0 for r in group_rows])
        lines.append(
            f"| {group} | {len({r.scenario_id for r in group_rows})} "
            f"| {sum(bool(r.passed) for r in group_rows) / len(group_rows):.1%} "
            f"| {group_accuracy.mean:.3f} | {group_counts.recall:.3f} |"
        )

    flaky = metrics.flaky_scenarios(passes)
    lines += [
        "",
        "### Flaky scenarios",
        "",
        "A scenario whose pass or fail flips between repeats. The prompt is underdetermined there.",
        "",
    ]
    lines += [f"- `{s}`" for s in flaky] if flaky else ["None."]
    lines += ["", f"<!-- rendered {datetime.now(UTC):%Y-%m-%d %H:%M} UTC -->", ""]
    return "\n".join(line for line in lines if line is not None)


def main() -> None:
    parser = argparse.ArgumentParser(description="Render the eval results table.")
    parser.add_argument("--run-id", type=int, default=None)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()

    run_id = args.run_id or latest_run_id()
    if run_id is None:
        args.output.write_text(EMPTY, encoding="utf-8")
        print(f"no runs in the database. wrote the placeholder to {args.output}")
        return

    from evals.persona import PersonaError, load_personas

    try:
        groups = {p.id: str(p.group) for p in load_personas()}
    except PersonaError:
        groups = {}

    with session_scope() as session:
        repo = EvalRepository(session)
        run = repo.get_run(run_id)
        if run is None:
            raise SystemExit(f"run {run_id} not found")
        rows = repo.results_for(run_id)
        if not rows:
            raise SystemExit(f"run {run_id} has no results")
        args.output.write_text(render_run(run, rows, groups), encoding="utf-8")
    print(f"wrote {args.output} from run {run_id}")


if __name__ == "__main__":
    main()
